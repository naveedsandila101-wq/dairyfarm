/**
 * Returns an inline SVG icon.
 *
 * @param string $name  Icon key.
 * @param string $class Extra class.
 * @return string
 */
function dairyfarm_icon( $name, $class = '' ) {
	$paths = dairyfarm_icon_paths();

	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}

	return sprintf(
		'<svg class="df-icon df-icon--%1$s %2$s" xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%3$s</svg>',
		esc_attr( $name ),
		esc_attr( $class ),
		$paths[ $name ] // Static, trusted markup.
	);
}

/**
 * Icons exposed to editors in block settings.
 *
 * @return array<int,array{label:string,value:string}>
 */
function dairyfarm_icon_choices() {
	$exclude = array( 'menu', 'close', 'chevron-down', 'chevron-left', 'chevron-right', 'expand', 'image', 'search', 'facebook', 'instagram', 'youtube', 'linkedin', 'x' );
	$choices = array();

	foreach ( array_keys( dairyfarm_icon_paths() ) as $name ) {
		if ( in_array( $name, $exclude, true ) ) {
			continue;
		}
		$choices[] = array(
			'label' => ucwords( str_replace( '-', ' ', $name ) ),
			'value' => $name,
		);
	}

	return $choices;
}
